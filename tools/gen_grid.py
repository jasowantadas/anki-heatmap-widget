"""Generates the size-specific widget grid layouts and GridSizes.kt. Run from the repo root."""
M = 'app/src/main'
L = f'{M}/res/layout'
sizes = range(4, 29)
for s in sizes:
    g = max(1.0, round(s * 0.18 * 2) / 2)
    ts = max(7, min(10, round(s * 0.65)))
    open(f'{L}/hm_cell_{s}.xml', 'w').write(f'''<?xml version="1.0" encoding="utf-8"?>
<ImageView xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/cell"
    android:layout_width="{s}dp"
    android:layout_height="{s}dp"
    android:paddingEnd="{g}dp"
    android:paddingBottom="{g}dp"
    android:scaleType="fitXY"
    android:src="@drawable/cell_l0" />
''')
    open(f'{L}/hm_space_{s}.xml', 'w').write(f'''<?xml version="1.0" encoding="utf-8"?>
<TextView xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="{s}dp"
    android:layout_height="18dp" />
''')
    open(f'{L}/hm_label_{s}.xml', 'w').write(f'''<?xml version="1.0" encoding="utf-8"?>
<TextView xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/label"
    android:layout_width="{3 * s}dp"
    android:layout_height="18dp"
    android:gravity="top|start"
    android:singleLine="true"
    android:textColor="#B4B2A9"
    android:textSize="10sp" />
''')
    rows = ''.join(f'''    <TextView android:layout_width="16dp" android:layout_height="{s}dp" android:gravity="center_vertical" android:includeFontPadding="false" android:text="{t}" android:textColor="#B4B2A9" android:textSize="{ts}sp" />
''' for t in ['', 'M', '', 'W', '', 'F', ''])
    open(f'{L}/hm_days_{s}.xml', 'w').write(f'''<?xml version="1.0" encoding="utf-8"?>
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="16dp"
    android:layout_height="wrap_content"
    android:orientation="vertical">
{rows}</LinearLayout>
''')


def arr(name, prefix):
    return f"    val {name} = intArrayOf(\n" + ''.join(f"        R.layout.{prefix}_{s},\n" for s in sizes) + "    )\n"


open(f'{M}/java/io/github/jasowantadas/ankiheatmap/GridSizes.kt', 'w').write(
    "package io.github.jasowantadas.ankiheatmap\n\n"
    "/** Generated by tools/gen_grid.py: one layout per square size (dp), from MIN to MAX. */\n"
    "object GridSizes {\n    const val MIN = %d\n    const val MAX = %d\n\n" % (min(sizes), max(sizes))
    + arr('CELL', 'hm_cell') + '\n' + arr('SPACE', 'hm_space') + '\n' + arr('LABEL', 'hm_label') + '\n'
    + arr('DAYS', 'hm_days') + "}\n")
